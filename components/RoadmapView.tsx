import React from 'react';
import { motion } from 'motion/react';
import type { CourseStatus, Roadmap, Stage } from '../types';
import { Icon } from './Icons';
import { ProgressRing } from './ProgressRing';

interface Props {
  roadmap: Roadmap;
  statuses: Record<string, CourseStatus>;
  onCourse: (name: string, status: CourseStatus) => void;
  onReset: () => void;
}

const STAGE_ICON: Record<Stage['id'], string> = { hs: 'school', mdc: 'building', certs: 'award', transfer: 'transfer', career: 'rocket' };
const NEXT: Record<CourseStatus, CourseStatus> = { pending: 'planned', planned: 'in-progress', 'in-progress': 'completed', completed: 'pending' };
const STATUS_STYLE: Record<CourseStatus, string> = {
  pending: 'bg-white text-slate-500 ring-slate-200',
  planned: 'bg-sky-50 text-sky-700 ring-sky-200',
  'in-progress': 'bg-amber-50 text-amber-800 ring-amber-300',
  completed: 'bg-emerald-50 text-emerald-800 ring-emerald-300',
};
const STATUS_LABEL: Record<CourseStatus, string> = { pending: 'To do', planned: 'Planned', 'in-progress': 'Taking now', completed: 'Done' };

const ENGINE_LABEL = (e: Roadmap['engine']) =>
  e.name === 'swarms' ? 'Personalized by Swarms multi-agent' :
  e.name === 'llm' ? `Personalized by ${e.detail.replace(/^prune\//, 'Prune → ').replace(/^gemini\//, 'Gemini ')}` :
  'Curated MDC catalog';

export const RoadmapView: React.FC<Props> = ({ roadmap, statuses, onCourse, onReset }) => {
  const mdc = roadmap.stages.find(s => s.id === 'mdc') as Extract<Stage, { id: 'mdc' }> | undefined;
  const courses = (mdc?.courses ?? []).map(c => ({ ...c, status: statuses[c.name] ?? c.status }));
  const done = courses.filter(c => c.status === 'completed').length;
  const progress = courses.length ? Math.round((done / courses.length) * 100) : 0;

  return (
    <article className="flex h-full flex-col overflow-hidden rounded-3xl bg-white ring-1 ring-slate-200">
      {/* header */}
      <header className="relative bg-navy-900 px-6 py-5 text-white">
        <div className="flex items-start gap-4">
          <div className="min-w-0 flex-1">
            <p className="text-xs font-medium uppercase tracking-wider text-amber-400">{roadmap.cluster}</p>
            <h2 className="mt-1 text-2xl font-bold">{roadmap.title}</h2>
            <p className="mt-1 text-sm text-slate-300">{roadmap.tagline}</p>
            <div className="mt-3 flex flex-wrap gap-2 text-xs">
              {roadmap.program && (
                <span className="rounded-full bg-white/10 px-2.5 py-1">MDC {roadmap.program.name} · {roadmap.program.code}</span>
              )}
              {roadmap.salary.median && (
                <a href={roadmap.salarySource.url} target="_blank" rel="noreferrer" title={roadmap.salarySource.label}
                   className="rounded-full bg-emerald-500/20 px-2.5 py-1 text-emerald-200 hover:bg-emerald-500/30">
                  Median ${roadmap.salary.median.toLocaleString()}/yr · BLS
                </a>
              )}
              <span className={`flex items-center gap-1 rounded-full px-2.5 py-1 ${roadmap.engine.name === 'catalog' ? 'bg-white/10' : 'bg-amber-500/20 text-amber-200'}`}>
                <Icon name={roadmap.engine.name === 'swarms' ? 'agents' : roadmap.engine.name === 'llm' ? 'bolt' : 'check'} className="h-3.5 w-3.5" />
                {ENGINE_LABEL(roadmap.engine)}
              </span>
            </div>
          </div>
          <ProgressRing value={progress} label="MDC done" />
        </div>
      </header>

      <div className="scroll-thin flex-1 overflow-y-auto px-6 py-5">
        {!roadmap.reviewed && (
          <p className="mb-4 flex gap-2 rounded-xl bg-amber-50 p-3 text-xs text-amber-900 ring-1 ring-amber-200">
            <Icon name="info" className="h-4 w-4 shrink-0" />
            This roadmap was generated by AI for a career outside our reviewed catalog. Double-check it with an MDC advisor.
          </p>
        )}

        {(roadmap.summary || roadmap.personalTips.length > 0) && (
          <motion.section initial={{ opacity: 0 }} animate={{ opacity: 1 }} className="mb-5 rounded-2xl bg-slate-50 p-4 ring-1 ring-slate-200">
            <h3 className="text-sm font-semibold text-slate-900">Your personal game plan</h3>
            {roadmap.summary && <p className="mt-1 text-sm text-slate-700">{roadmap.summary}</p>}
            <ul className="mt-2 space-y-1.5">
              {roadmap.personalTips.map((t, i) => (
                <li key={i} className="flex gap-2 text-sm text-slate-700"><Icon name="check" className="mt-0.5 h-4 w-4 shrink-0 text-emerald-600" />{t}</li>
              ))}
            </ul>
          </motion.section>
        )}

        <ol className="relative space-y-5 border-l-2 border-slate-200 pl-6">
          {roadmap.stages.map((s, i) => (
            <motion.li
              key={s.id}
              initial={{ opacity: 0, x: -10 }}
              animate={{ opacity: 1, x: 0 }}
              transition={{ delay: 0.08 * i }}
              className="relative"
            >
              <span className="absolute -left-[39px] grid h-8 w-8 place-items-center rounded-full bg-navy-900 text-amber-400 ring-4 ring-white">
                <Icon name={STAGE_ICON[s.id]} className="h-4 w-4" />
              </span>
              <p className="text-[11px] font-semibold uppercase tracking-wider text-slate-500">Step {i + 1}</p>
              <h3 className="text-base font-semibold text-slate-900">{s.title}</h3>

              {(s.id === 'hs' || s.id === 'certs') && (
                <ul className="mt-2 flex flex-wrap gap-1.5">
                  {s.items.map(x => <li key={x} className="rounded-lg bg-slate-100 px-2.5 py-1 text-sm text-slate-700">{x}</li>)}
                </ul>
              )}

              {s.id === 'mdc' && (
                <div className="mt-1">
                  <p className="text-sm font-medium text-navy-800">{s.credential}</p>
                  <p className="text-sm text-slate-600">{s.notes}</p>
                  <p className="mt-2 text-xs text-slate-500">Tap a course to cycle: To do → Planned → Taking now → Done</p>
                  <ul className="mt-2 grid gap-1.5 sm:grid-cols-2">
                    {courses.map(c => (
                      <li key={c.name}>
                        <button
                          onClick={() => onCourse(c.name, NEXT[c.status])}
                          className={`flex w-full items-center justify-between gap-2 rounded-xl px-3 py-2 text-left text-sm ring-1 transition-colors ${STATUS_STYLE[c.status]}`}
                        >
                          <span className={c.status === 'completed' ? 'line-through decoration-emerald-600/50' : ''}>{c.name}</span>
                          <span className="shrink-0 text-[11px] font-medium">{STATUS_LABEL[c.status]}</span>
                        </button>
                      </li>
                    ))}
                  </ul>
                </div>
              )}

              {s.id === 'transfer' && (
                <div className="mt-2 grid gap-2 sm:grid-cols-2">
                  {s.options.map(o => (
                    <div key={o.name + o.program} className="rounded-xl p-3 ring-1 ring-slate-200">
                      <p className="text-sm font-semibold text-slate-900">{o.name}</p>
                      <p className="text-sm text-slate-700">{o.program}</p>
                      <p className="mt-1 text-xs text-slate-500">{o.note}</p>
                    </div>
                  ))}
                </div>
              )}

              {s.id === 'career' && (
                <div className="mt-2">
                  <ol className="flex flex-wrap items-center gap-1.5 text-sm">
                    {s.items.map((x, j) => (
                      <React.Fragment key={x}>
                        <li className="rounded-lg bg-emerald-50 px-2.5 py-1 text-emerald-900 ring-1 ring-emerald-200">{x}</li>
                        {j < s.items.length - 1 && <span aria-hidden className="text-slate-400">→</span>}
                      </React.Fragment>
                    ))}
                  </ol>
                  {s.license && <p className="mt-2 text-xs text-slate-600"><strong>License:</strong> {s.license}</p>}
                </div>
              )}
            </motion.li>
          ))}
        </ol>

        <footer className="mt-6 flex flex-wrap items-center justify-between gap-3 border-t border-slate-200 pt-4 text-xs text-slate-500">
          <p className="max-w-xl">{roadmap.disclaimer}</p>
          <button onClick={onReset} className="flex items-center gap-1 rounded-lg px-2 py-1 text-slate-600 hover:bg-slate-100">
            <Icon name="reset" className="h-3.5 w-3.5" /> Reset progress
          </button>
        </footer>
      </div>
    </article>
  );
};
