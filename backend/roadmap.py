"""Career -> MDC roadmap engine.

Every roadmap starts from the curated catalog in data/careers.json, so the facts the UI shows
come from a reviewed source. AI then personalizes it:

1. Swarms (SWARMS_API_KEY): a 3-agent SequentialWorkflow
   Career Researcher -> MDC Pathway Planner -> Transfer & Outcomes Advisor.
2. Otherwise the LLM provider chain (Prune / Gemini / OpenRouter) in one call.
3. Otherwise the catalog roadmap is returned as-is (engine = "catalog").

Careers not in the catalog are generated by AI from scratch and flagged as unreviewed.
"""
from __future__ import annotations

import copy
import json
import os
import re
import threading
import time
from collections import OrderedDict
from difflib import SequenceMatcher
from pathlib import Path

import requests

import llm

CATALOG = json.loads((Path(__file__).parent / "data" / "careers.json").read_text(encoding="utf-8"))
CAREERS = {c["id"]: c for c in CATALOG["careers"]}
SWARMS_URL = os.getenv("SWARMS_BASE_URL", "https://api.swarms.world") + "/v1/swarm/completions"


def career_cards() -> list[dict]:
    return [{k: c[k] for k in ("id", "title", "icon", "cluster", "tagline", "program")} | {"salary": c["salary"]}
            for c in CATALOG["careers"]]


def find_career(query: str) -> dict | None:
    q = query.lower().strip()
    if not q:
        return None
    if q in CAREERS:
        return CAREERS[q]
    best, best_score = None, 0.0
    for c in CATALOG["careers"]:
        names = [c["title"].lower(), c["id"].replace("-", " ")] + [k.lower() for k in c["keywords"]]
        for n in names:
            score = 1.0 if (n in q or q in n) and len(min(n, q, key=len)) >= 3 else SequenceMatcher(None, q, n).ratio()
            if score > best_score:
                best, best_score = c, score
    return best if best_score >= 0.72 else None


def base_roadmap(c: dict) -> dict:
    prog = CATALOG["programs"].get(c["program"]) if c.get("program") else None
    return {
        "careerId": c["id"],
        "title": c["title"],
        "tagline": c["tagline"],
        "cluster": c["cluster"],
        "program": ({"key": c["program"], "name": prog["name"], "code": prog["code"]} if prog else None),
        "salary": c["salary"],
        "salarySource": CATALOG["salary_source"],
        "stages": [
            {"id": "hs", "title": "High school prep", "items": c["highSchool"]},
            {"id": "mdc", "title": "Start at Miami Dade College", "credential": c["mdc"]["credential"],
             "notes": c["mdc"]["notes"], "courses": [{"name": n, "status": "pending"} for n in c["mdc"]["courses"]]},
            {"id": "certs", "title": "Certifications & experience", "items": c["certifications"]},
            {"id": "transfer", "title": "Transfer for a bachelor's", "options": c["transfer"]},
            {"id": "career", "title": "Launch your career", "items": c["career"], "license": c.get("license")},
        ],
        "personalTips": [],
        "reviewed": True,
        "disclaimer": CATALOG["disclaimer"],
        "engine": {"name": "catalog", "detail": "Curated MDC catalog"},
    }


def _profile_text(profile: dict) -> str:
    parts = []
    if profile.get("grade"):
        parts.append(f"grade {profile['grade']}")
    if profile.get("interests"):
        parts.append("interests: " + ", ".join(map(str, profile["interests"]))[:300])
    if profile.get("completed"):
        parts.append("already completed: " + ", ".join(map(str, profile["completed"]))[:300])
    return "; ".join(parts) or "no profile given"


def _extract_json(raw) -> dict | None:
    """Find the last JSON object in a model/swarm output (string, list or dict)."""
    if isinstance(raw, dict) and ("tips" in raw or "stages" in raw):
        return raw
    text = raw if isinstance(raw, str) else json.dumps(raw)
    dec = json.JSONDecoder()
    found = None
    for m in re.finditer(r"\{", text):
        try:
            obj, _ = dec.raw_decode(text[m.start():])
            if isinstance(obj, dict) and ("tips" in obj or "stages" in obj or "title" in obj):
                found = obj
        except ValueError:
            continue
    if found is None and not isinstance(raw, str):
        # swarm outputs are often lists of {role, content}; search each content string
        for item in raw if isinstance(raw, list) else []:
            content = item.get("content") if isinstance(item, dict) else item
            if isinstance(content, str):
                found = _extract_json(content) or found
    return found


def _agent_steps(output, agents: list[dict]) -> list[dict]:
    """Turn the swarm transcript into [{agent, role, summary}] for the UI's 'how the agents worked' view."""
    import safety
    descr = {a["agent_name"]: a.get("description", "") for a in agents}
    steps = []
    for item in output if isinstance(output, list) else []:
        if not isinstance(item, dict):
            continue
        name = str(item.get("role") or item.get("agent_name") or "")
        if name not in descr:
            continue  # skip the echoed user task
        text = item.get("content")
        text = text if isinstance(text, str) else json.dumps(text, ensure_ascii=False)
        text = re.sub(r"```(?:json)?|```", "", text).strip()
        parsed = _extract_json(text) if "{" in text else None
        if parsed and (parsed.get("tips") or parsed.get("summary")):  # final agent: show prose, not JSON
            text = " ".join(filter(None, [parsed.get("summary"), *(f"- {t}" for t in parsed.get("tips") or [])]))
        steps.append({"agent": name, "role": descr[name], "summary": safety.scrub_output(text, [])[:700]})
    return steps


TIPS_SCHEMA = ('Return ONLY JSON: {"tips": [3-5 short, specific, encouraging tips for THIS student, plain text], '
               '"firstSemester": [3-4 course names taken from the roadmap], "summary": "2 sentences"}')


def _apply_tips(rm: dict, data: dict | None) -> dict:
    if not data:
        return rm
    rm["personalTips"] = [str(t)[:280] for t in (data.get("tips") or [])][:5]
    first = {str(x).lower() for x in (data.get("firstSemester") or [])}
    for course in rm["stages"][1]["courses"]:
        if course["name"].lower() in first:
            course["status"] = "planned"
    if data.get("summary"):
        rm["summary"] = str(data["summary"])[:500]
    return rm


def _swarms(rm: dict, profile: dict) -> dict | None:
    key = os.getenv("SWARMS_API_KEY", "").strip()
    if not key:
        return None
    # gpt-4.1-mini: ~7s for the 3-agent run vs ~20s on the Swarms default model
    model = os.getenv("SWARMS_MODEL", "gpt-4.1-mini").strip()
    # no temperature: the Swarms default model (claude-sonnet-5) rejects it with a 500
    base = {"max_loops": 1, "max_tokens": 600}
    if model:
        base["model_name"] = model
    agents = [
        {"agent_name": "Career Researcher", "description": "Explains the career to a teenager",
         "system_prompt": "You research careers for Miami high-school students. Summarize what the job is like day to day, "
                          "the skills that matter, and how the student's interests connect. Be concise and accurate.", **base},
        {"agent_name": "MDC Pathway Planner", "description": "Maps MDC courses and sequencing",
         "system_prompt": "You are a Miami Dade College academic planner. Using ONLY the course list in the roadmap, pick the "
                          "best first-semester courses for this student and note prerequisites to watch.", **base},
        {"agent_name": "Transfer and Outcomes Advisor", "description": "Writes the final personalized plan",
         "system_prompt": "You combine the previous agents' work into final advice for the student. " + TIPS_SCHEMA, **base},
    ]
    payload = {
        "name": "MDC Pathway Navigator",
        "description": "Builds a personalized MDC-first career roadmap",
        "swarm_type": "SequentialWorkflow",
        "agents": agents,
        "max_loops": 1,
        "task": f"Career: {rm['title']}\nStudent: {_profile_text(profile)}\nRoadmap (from the MDC catalog):\n"
                + json.dumps({s['id']: s for s in rm['stages']})[:6000],
    }
    swarm_timeout = float(os.getenv("SWARMS_TIMEOUT_SECONDS", "40"))
    try:
        t0 = time.monotonic()
        for attempt in range(2):  # one retry on a fast transient 5xx only
            r = requests.post(SWARMS_URL, headers={"x-api-key": key, "Content-Type": "application/json"},
                              json=payload, timeout=swarm_timeout)
            if r.status_code < 500 or time.monotonic() - t0 > swarm_timeout / 3:
                break
            print(f"[swarms] HTTP {r.status_code} (attempt {attempt + 1}): {r.text[:300]}")
        r.raise_for_status()
        body = r.json()
        data = _extract_json(body.get("output"))
        if not data:
            print("[swarms] no JSON in output")
            return None
        rm = _apply_tips(rm, data)
        usage = body.get("usage") or {}
        rm["engine"] = {"name": "swarms", "detail": f"Swarms SequentialWorkflow, {len(agents)} agents",
                        "seconds": body.get("execution_time"), "jobId": body.get("job_id"),
                        "model": model or "swarms-default",
                        "usage": {"totalTokens": usage.get("total_tokens"), "costUsd": usage.get("total_cost")}}
        rm["agentSteps"] = _agent_steps(body.get("output"), agents)
        return rm
    except Exception as e:
        print(f"[swarms] failed: {type(e).__name__}: {str(e)[:200]}")
        return None


def _llm_tips(rm: dict, profile: dict) -> dict | None:
    if not llm.available_providers():
        return None
    msgs = [
        {"role": "system", "content": "You are an MDC academic planner for high-school students. Only use courses listed in the roadmap. " + TIPS_SCHEMA},
        {"role": "user", "content": f"Career: {rm['title']}\nStudent: {_profile_text(profile)}\nRoadmap: "
                                    + json.dumps({s['id']: s for s in rm['stages']})[:6000]},
    ]
    meta: dict = {}
    try:
        content, used = llm.complete(msgs, temperature=0.4, max_tokens=700, meta_out=meta)
        rm = _apply_tips(rm, _extract_json(content))
        rm["engine"] = {"name": "llm", "detail": used, **({"prune": meta["prune"]} if meta.get("prune") else {})}
        return rm
    except llm.LLMUnavailable:
        return None


def _generate_unknown(query: str, profile: dict) -> dict | None:
    """AI-generated roadmap for a career that isn't in the catalog."""
    if not llm.available_providers():
        return None
    shape = ('{"title": str, "tagline": str, "cluster": str, "highSchool": [str], "credential": str, "notes": str, '
             '"courses": [str], "certifications": [str], "transfer": [{"name": str, "program": str, "note": str}], '
             '"career": [str], "license": str|null}')
    msgs = [
        {"role": "system", "content": "You build step-by-step career roadmaps that START at Miami Dade College (MDC) for Miami "
                                      "high-school students. Prefer MDC programs and FIU/UM transfer paths. If unsure of an "
                                      f"exact course code, describe the course without a code. Return ONLY JSON shaped like {shape}."},
        {"role": "user", "content": f"Career: {query[:120]}\nStudent: {_profile_text(profile)}"},
    ]
    meta: dict = {}
    try:
        content, used = llm.complete(msgs, temperature=0.4, max_tokens=1400, meta_out=meta)
        d = _extract_json(content) or {}
        c = {
            "id": "custom-" + re.sub(r"[^a-z0-9]+", "-", query.lower()).strip("-")[:40],
            "title": d.get("title") or query.title(), "icon": "compass", "cluster": d.get("cluster", "Custom"),
            "tagline": d.get("tagline", ""), "program": None, "keywords": [],
            "salary": {"median": None, "occupation": "Check bls.gov/ooh for this occupation"},
            "highSchool": d.get("highSchool", []),
            "mdc": {"credential": d.get("credential", "Associate in Arts (AA)"), "notes": d.get("notes", ""), "courses": d.get("courses", [])},
            "certifications": d.get("certifications", []), "transfer": d.get("transfer", []),
            "career": d.get("career", []), "license": d.get("license"),
        }
        rm = base_roadmap(c)
        rm["reviewed"] = False
        rm["engine"] = {"name": "llm", "detail": used, **({"prune": meta["prune"]} if meta.get("prune") else {})}
        return rm
    except llm.LLMUnavailable:
        return None


class _TTLCache:
    """Small thread-safe LRU+TTL cache for AI results (repeat demo clicks are instant and free)."""

    def __init__(self, size: int = 200, ttl: float = 3600):
        self.size, self.ttl = size, ttl
        self._d: OrderedDict = OrderedDict()
        self._lock = threading.Lock()

    def get(self, key):
        with self._lock:
            hit = self._d.get(key)
            if not hit or hit[0] < time.monotonic():
                self._d.pop(key, None)
                return None
            self._d.move_to_end(key)
            return copy.deepcopy(hit[1])

    def put(self, key, value):
        with self._lock:
            self._d[key] = (time.monotonic() + self.ttl, copy.deepcopy(value))
            self._d.move_to_end(key)
            while len(self._d) > self.size:
                self._d.popitem(last=False)

    def clear(self):
        with self._lock:
            self._d.clear()


CACHE = _TTLCache(ttl=float(os.getenv("ROADMAP_CACHE_SECONDS", "3600")))


def _cache_key(kind: str, ident: str, profile: dict) -> tuple:
    interests = tuple(sorted(str(i).strip().lower() for i in (profile.get("interests") or [])))
    return kind, ident.lower(), str(profile.get("grade") or ""), interests


def build(career_id: str | None, query: str | None, profile: dict, *, personalize: bool = True) -> dict | None:
    c = CAREERS.get(career_id or "") or (find_career(query) if query else None)
    if c is None:
        if not query:
            return None
        key = _cache_key("custom", query, profile)
        rm = CACHE.get(key)
        if rm is None:
            rm = _generate_unknown(query, profile)
            if rm:
                CACHE.put(key, rm)
        return rm
    rm = base_roadmap(c)
    if not personalize:
        return rm
    key = _cache_key("career", c["id"], profile)
    cached = CACHE.get(key)
    if cached:
        cached["cached"] = True
        return cached
    out = _swarms(rm, profile) or _llm_tips(rm, profile) or rm
    if out["engine"]["name"] != "catalog":  # only cache real AI output; retry AI next time otherwise
        CACHE.put(key, out)
    return out
